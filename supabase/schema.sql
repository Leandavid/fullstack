-- Esquema de BuenPlan en Supabase.
-- Ejecuta este archivo completo en el SQL Editor del proyecto.
--
-- Las cuentas de clientes viven en Supabase Auth (auth.users). La tabla
-- public.users guarda su perfil público y los enlaza con auth_user_id.
-- El backend trabaja con la service_role key y estas tablas tienen RLS activado
-- sin políticas públicas: el navegador nunca consulta Supabase directamente.

create table if not exists public.offers (
  id text primary key,
  brand text not null,
  brand_initials text not null,
  brand_color text not null,
  title text not null,
  category text not null,
  discount_label text not null,
  description text not null,
  terms text not null,
  image_url text not null,
  location text not null,
  expires_at date not null,
  featured boolean not null default false,
  active boolean not null default true,
  views integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.users (
  id text primary key,
  auth_user_id uuid unique references auth.users (id) on delete cascade,
  username text not null unique,
  display_name text not null,
  email text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.redemptions (
  id bigint generated by default as identity primary key,
  offer_id text not null references public.offers (id) on delete cascade,
  user_id text not null references public.users (id) on delete cascade,
  code text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.subscriptions (
  id bigint generated by default as identity primary key,
  email text not null,
  created_at timestamptz not null default now()
);

create unique index if not exists subscriptions_email_unique on public.subscriptions (lower(email));

create table if not exists public.businesses (
  brand text primary key,
  contact text not null default '',
  verified boolean not null default false,
  password_salt text,
  password_hash text,
  created_at timestamptz not null default now()
);

create table if not exists public.business_sessions (
  token text primary key,
  brand text not null references public.businesses (brand) on delete cascade,
  expires_at timestamptz not null
);

create table if not exists public.user_sessions (
  token text primary key,
  user_id text not null references public.users (id) on delete cascade,
  expires_at timestamptz not null
);

create index if not exists offers_active_brand_idx on public.offers (active, brand);
create index if not exists offers_active_category_idx on public.offers (active, category);
create index if not exists redemptions_user_idx on public.redemptions (user_id);
create index if not exists redemptions_offer_idx on public.redemptions (offer_id);
create index if not exists business_sessions_expires_idx on public.business_sessions (expires_at);
create index if not exists user_sessions_expires_idx on public.user_sessions (expires_at);

-- Migración desde la versión con contraseñas propias:
-- los usuarios ahora viven en Supabase Auth y el backend ya no guarda sus hashes.
alter table public.users add column if not exists auth_user_id uuid unique references auth.users (id) on delete cascade;
alter table public.users drop column if exists password_salt;
alter table public.users drop column if exists password_hash;

-- Suma una visita de forma atómica, sin leer y reescribir desde el backend.
create or replace function public.increment_offer_views(p_offer_id text)
returns void
language sql
security definer
set search_path = public
as $$
  update public.offers
  set views = views + 1
  where id = p_offer_id and active = true;
$$;

alter table public.offers enable row level security;
alter table public.users enable row level security;
alter table public.redemptions enable row level security;
alter table public.subscriptions enable row level security;
alter table public.businesses enable row level security;
alter table public.business_sessions enable row level security;
alter table public.user_sessions enable row level security;

-- Solo el backend (service_role) puede tocar estas tablas. No crees políticas
-- para anon: el catálogo se sirve a través de la API de Node, no de Supabase.
grant usage on schema public to service_role;
grant all on all tables in schema public to service_role;
grant all on all sequences in schema public to service_role;
revoke all on function public.increment_offer_views(text) from public, anon, authenticated;
grant execute on function public.increment_offer_views(text) to service_role;
